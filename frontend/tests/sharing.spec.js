import { test, expect } from '@playwright/test'
import path from 'node:path'
let createdTask
test.afterEach(async ({ page }) => {
  if (createdTask) await page.request.delete('/api/tasks/' + createdTask, { headers: { 'X-Liner-Client': 'desktop' } })
  createdTask = null
})

test('complete every page, login, submit full model and refresh review status', async ({ page }) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/session?token=e2e-local-token')
  const imported = page.waitForResponse(r => r.url().endsWith('/api/tasks/import') && r.request().method() === 'POST')
  await page.getByLabel('选择说明书或项目文件').setInputFiles(path.resolve('../artifacts/e2e-manual.pdf'))
  createdTask = (await (await imported).json()).id
  await page.getByRole('button', { name: '分享广场', exact: true }).click()
  await expect(page.getByText('逐页校对 0 / 2', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '提交审核', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '添加标记框', exact: true }).click()
  await page.getByLabel('板件', { exact: true }).fill('A1')
  await page.getByLabel('零件号', { exact: true }).fill('003')
  await page.getByLabel('分类', { exact: true }).selectOption('头')
  await page.getByLabel('数量', { exact: true }).fill('2')
  await page.getByRole('button', { name: '确认本页完成', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认本页完成', exact: true }).click()
  await expect(page.getByRole('button', { name: '本页已确认完成', exact: true })).toBeDisabled()
  await page.getByLabel('数量', { exact: true }).fill('3')
  await expect(page.getByRole('button', { name: '确认本页完成', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '确认本页完成', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认本页完成', exact: true }).click()
  await page.getByRole('button', { name: '第 2 页', exact: true }).click()
  await page.getByRole('button', { name: '确认本页完成', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('button', { name: '确认本页完成', exact: true })).toBeDisabled()
  await page.getByLabel('本页没有取件内容的原因').fill('封底和工具说明')
  await page.getByRole('dialog').getByRole('button', { name: '确认本页完成', exact: true }).click()
  await page.getByRole('button', { name: '分享广场', exact: true }).click()
  await expect(page.getByText('逐页校对 2 / 2', { exact: true })).toBeVisible()
  await page.getByLabel('手机号 / 邮箱 / 账号').fill('test@example.com')
  await page.getByLabel('登录密码', { exact: true }).fill('fixture-password')
  await page.getByRole('button', { name: '登录平台', exact: true }).click()
  await expect(page.getByText('已登录：测试分享作者（7）')).toBeVisible()
  await page.getByLabel('模型名称', { exact: true }).fill('MG 测试机体')
  await expect(page.getByRole('button', { name: '提交审核', exact: true })).toBeDisabled()
  await page.getByRole('checkbox').check()
  await page.screenshot({ path: '../artifacts/desktop-sharing-v0.1.4.png', fullPage: true })
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  await expect(page.getByText('等待审核', { exact: true })).toBeVisible()
  await page.request.post('/api/test/share-review', { headers: { 'X-Liner-Client': 'desktop' }, data: {} })
  await page.getByRole('button', { name: '刷新审核状态', exact: true }).click()
  await expect(page.getByText('审核通过 · 已奖励 5 张 AI 生成卡', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: '查看广场分享' })).toHaveAttribute('href', 'https://agamaship.com/square/901')
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('button', { name: '使用平台 JWT', exact: true }).click()
  await page.getByLabel('平台 JWT', { exact: true }).fill('expired-token')
  await page.getByRole('button', { name: '登录平台', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('登录已失效')
  expect(errors).toEqual([])
})
