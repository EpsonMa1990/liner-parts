test('recognition on one page allows other pages to draw, save, run, queue and cancel independently', async ({ page }) => {
  const headers = { 'X-Liner-Client': 'desktop' }
  let releaseSnapshot = () => {}
  let releaseNextPoll = () => {}
  await page.goto('/session?token=e2e-local-token')
  await page.request.put('/api/settings', { headers, data: { model: 'fixture-held', base_url: 'http://127.0.0.1:9999/v1' } })
  const imported = page.waitForResponse(r => r.url().endsWith('/api/tasks/import') && r.request().method() === 'POST')
  await page.getByLabel('选择说明书图片', { exact: true }).setInputFiles([
    path.resolve('../artifacts/e2e-page-2.png'), path.resolve('../artifacts/e2e-page-10.png'),
  ])
  const task = await (await imported).json()
  const state = async () => (await page.request.get(`/api/tasks/${task.id}/recognition-state`)).json()
  const submit = async () => {
    const response = page.waitForResponse(r => r.url().endsWith(`/api/tasks/${task.id}/recognize`) && r.request().method() === 'POST')
    await page.getByRole('button', { name: '识别本页未完成项', exact: true }).click()
    return (await response).json()
  }
  try {
    await page.getByRole('button', { name: '添加标记框', exact: true }).click()
    const first = await submit()
    await expect.poll(async () => (await state()).jobs.find(job => job.id === first.id).status).toBe('running')
    await expect(page.getByRole('button', { name: '添加标记框', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: '追加图片', exact: true })).toBeEnabled()
    await page.getByLabel('追加说明书图片', { exact: true }).setInputFiles(path.resolve('../artifacts/e2e-page-11.png'))
    await expect(page.getByRole('button', { name: '第 3 页', exact: true })).toHaveAttribute('aria-current', 'page')
    await page.getByRole('button', { name: '第 2 页', exact: true }).click()
    await expect(page.getByRole('button', { name: '画框模式', exact: true })).toBeEnabled()
    const paper = page.getByRole('group', { name: /说明书标注区/ })
    await expect.poll(() => paper.locator('img').evaluate(img => img.naturalWidth)).toBeGreaterThan(0)
    const rect = await paper.boundingBox()
    await page.mouse.move(rect.x+rect.width*.1, rect.y+rect.height*.14)
    await page.mouse.down()
    await page.mouse.move(rect.x+rect.width*.4, rect.y+rect.height*.23, { steps: 6 })
    await page.mouse.up()
    await page.getByLabel('分类', { exact: true }).selectOption('背包2')
    await page.getByLabel('数量', { exact: true }).fill('4')
    await page.getByLabel('数量', { exact: true }).blur()
    const second = await submit()
    await expect.poll(async () => (await state()).jobs.filter(job => job.status === 'running').length).toBe(2)
    await page.getByRole('button', { name: '第 3 页', exact: true }).click()
    await page.getByRole('button', { name: '添加标记框', exact: true }).click()
    const queued = await submit()
    await expect.poll(async () => (await state()).jobs.find(job => job.id === queued.id).status).toBe('queued')
    await expect(page.getByRole('button', { name: '本页排队中', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: '取消第 3 页识别', exact: true }).click()
    await expect(page.getByLabel('数量', { exact: true })).toBeEnabled()
    await page.getByLabel('数量', { exact: true }).fill('7')
    await page.getByLabel('数量', { exact: true }).blur()
    const third = await submit()
    await expect.poll(async () => (await state()).jobs.find(job => job.id === third.id).status).toBe('queued')
    const firstPage = await (await page.request.get(`/api/pages/${task.pages[0].id}`)).json()
    await page.request.post('/api/test/release', { headers, data: { box_id: firstPage.boxes[0].id } })
    await expect.poll(async () => (await state()).jobs.find(job => job.id === third.id).status).toBe('running')
    expect((await state()).jobs.find(job => job.id === second.id).status).toBe('running')
    await page.getByRole('button', { name: '第 1 页', exact: true }).click()
    await page.locator('.box-row').click()
    await expect(page.getByLabel('零件号', { exact: true })).toHaveValue('01')
    await expect(page.getByLabel('数量', { exact: true })).toBeEnabled()

    // Delay a real old snapshot until AFTER a new edit has already been saved.
    // A late background response must neither erase the edit nor lower its revision.
    let captured
    const capture = new Promise(resolve => captured = resolve)
    const heldSnapshot = new Promise(resolve => releaseSnapshot = resolve)
    let nextPollStarted
    const nextPoll = new Promise(resolve => nextPollStarted = resolve)
    const holdNextPoll = new Promise(resolve => releaseNextPoll = resolve)
    let snapshotDelivered = false, nextHeld = false
    let intercept = true
    await page.route('**/recognition-state?*', async route => {
      if (intercept && route.request().url().includes(task.pages[0].id)) {
        intercept = false
        const response = await route.fetch()
        captured()
        await heldSnapshot
        await route.fulfill({ response })
        snapshotDelivered = true
      } else {
        if (snapshotDelivered && !nextHeld) {
          nextHeld = true
          nextPollStarted()
          await holdNextPoll
        }
        await route.continue()
      }
    })
    await capture
    await page.getByLabel('数量', { exact: true }).fill('9')
    await page.getByLabel('数量', { exact: true }).blur()
    await expect.poll(async () => (await (await page.request.get(`/api/pages/${task.pages[0].id}`)).json()).boxes[0].quantity).toBe(9)
    releaseSnapshot()
    await nextPoll  // the old response has been handled; hold the next refresh to expose any clobber
    await expect(page.getByLabel('数量', { exact: true })).toHaveValue('9')
    releaseNextPoll()
    await page.screenshot({ path: '../artifacts/concurrent-recognition-v0.1.3.png', fullPage: true })
    await page.request.post('/api/test/release', { headers, data: {} })
    await expect.poll(async () => (await state()).jobs.filter(job => ['running','queued','cancelling'].includes(job.status)).length).toBe(0)
    await page.getByRole('button', { name: '第 2 页', exact: true }).click()
    await page.locator('.box-row').click()
    await expect(page.getByLabel('零件号', { exact: true })).toHaveValue('02')
    await expect(page.getByLabel('数量', { exact: true })).toHaveValue('4')
    await expect(page.getByLabel('分类', { exact: true })).toHaveValue('背包2')
    await page.getByRole('button', { name: '第 3 页', exact: true }).click()
    await page.locator('.box-row').click()
    await expect(page.getByLabel('零件号', { exact: true })).toHaveValue('03')
    await expect(page.getByLabel('数量', { exact: true })).toHaveValue('7')
    await page.getByRole('button', { name: '第 1 页', exact: true }).click()
    await expect(page.locator('.box-row')).toContainText('9 件')
  } finally {
    releaseSnapshot()
    releaseNextPoll()
    await page.request.post('/api/test/release', { headers, data: {} })
    await page.request.put('/api/settings', { headers, data: { model: 'fixture-vision' } })
  }
})
